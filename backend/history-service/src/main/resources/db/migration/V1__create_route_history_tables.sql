CREATE TABLE route_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_route_plan_id BIGINT NOT NULL UNIQUE,
    trip_id BIGINT NOT NULL,
    total_distance_m BIGINT NOT NULL,
    driving_time_s BIGINT NOT NULL,
    service_time_s BIGINT NOT NULL,
    total_time_s BIGINT NOT NULL,
    calculated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE TABLE route_history_stops (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_history_id BIGINT NOT NULL,
    delivery_id BIGINT NOT NULL,
    stop_order INTEGER NOT NULL,
    address VARCHAR(255) NOT NULL,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    CONSTRAINT fk_route_history_stops_route_history
        FOREIGN KEY (route_history_id)
        REFERENCES route_history (id)
        ON DELETE CASCADE,
    CONSTRAINT uk_route_history_stops_route_order
        UNIQUE (route_history_id, stop_order)
);

CREATE INDEX idx_route_history_stops_route_history_id
    ON route_history_stops (route_history_id);

CREATE INDEX idx_route_history_trip_id
    ON route_history (trip_id);
CREATE TABLE deliveries
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    recipient_name   VARCHAR(100)     NOT NULL,
    recipient_phone  VARCHAR(20)      NOT NULL,

    street           VARCHAR(100)     NOT NULL,
    building_number  VARCHAR(10)      NOT NULL,
    apartment_number VARCHAR(10),
    postal_code      VARCHAR(10)      NOT NULL,
    city             VARCHAR(100)     NOT NULL,
    country          VARCHAR(60)      NOT NULL,

    latitude         DOUBLE PRECISION NOT NULL,
    longitude        DOUBLE PRECISION NOT NULL,

    size             VARCHAR(1)       NOT NULL
        CHECK (size IN ('S', 'M', 'L')),

    status           VARCHAR(20)      NOT NULL DEFAULT 'ADDED'
        CHECK (status IN ('ADDED', 'IN_DELIVERY', 'DELIVERED'))
);

CREATE TABLE vehicles
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand                VARCHAR(50)  NOT NULL,
    model                VARCHAR(50)  NOT NULL,
    capacity             INT         NOT NULL CHECK (capacity > 0),
    registration_number  VARCHAR(10) NOT NULL UNIQUE,
    is_active            BOOLEAN     NOT NULL DEFAULT TRUE,
    courier_keycloak_id  VARCHAR(255)
);

CREATE TABLE trips
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT      NOT NULL REFERENCES vehicles (id),
    status     VARCHAR(20) NOT NULL DEFAULT 'ADDED'
        CHECK (status IN ('ADDED', 'FINISHED'))
);

CREATE TABLE trip_deliveries
(
    trip_id     BIGINT NOT NULL REFERENCES trips (id),
    delivery_id BIGINT NOT NULL REFERENCES deliveries (id),

    PRIMARY KEY (trip_id, delivery_id),
    UNIQUE (delivery_id)
);
